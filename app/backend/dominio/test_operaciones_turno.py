    def test_modification_and_cancellation_rollback(self):
        turno = self.turn()
        target = self.target()
        for position in (1, 2):
            actual = Disponibilidad.save
            calls = []
            def fail(instance, *args, **kwargs):
                calls.append(instance.pk)
                result = actual(instance, *args, **kwargs)
                if len(calls) == position:
                    raise RuntimeError('after write')
                return result
            with patch.object(Disponibilidad, 'save', fail), self.assertRaises(RuntimeError):
                modificar_turno(self.users['PACIENTE'], turno.pk, target.pk)
            self.block.refresh_from_db(); target.refresh_from_db(); turno.refresh_from_db()
            self.assertEqual((self.block.estado, target.estado, turno.disponibilidad_id), ('OCUPADO', 'DISPONIBLE', self.block.pk))
        with patch.object(Turno, 'save', side_effect=RuntimeError('turn write')):
            with self.assertRaises(RuntimeError):
                modificar_turno(self.users['PACIENTE'], turno.pk, target.pk)
            with self.assertRaises(RuntimeError):
                cancelar_turno(self.users['PACIENTE'], turno.pk)
        self.block.refresh_from_db(); target.refresh_from_db(); turno.refresh_from_db()
        self.assertEqual((self.block.estado, target.estado, turno.estado), ('OCUPADO', 'DISPONIBLE', 'RESERVADO'))

