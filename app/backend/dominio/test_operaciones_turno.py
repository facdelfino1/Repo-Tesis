    def turn(self, today=False):
        self.assertEqual(self.reserve().status_code, 201)
        turno = Turno.objects.get(disponibilidad=self.block)
        if today:
            self.block.fecha = timezone.localdate()
            self.block.save(update_fields=['fecha'])
            turno.fecha = self.block.fecha
            turno.save(update_fields=['fecha'])
        return turno

    def login(self, role):
        self.client.force_login(self.users[role], backend='dominio.authentication.CuentaBackend')

    def call(self, action, turno, data=None, nested=True, doctor=None):
        name = 'turno-agenda-' if nested else 'turno-'
        kwargs = {'pk': turno.pk}
        if nested:
            kwargs['medico_pk'] = (doctor or self.doctor).pk
        return self.client.post(reverse(name + action, kwargs=kwargs), data or {}, format='json',
            HTTP_X_CSRFTOKEN=self.client.cookies['csrftoken'].value)

    def target(self, doctor=None):
        return Disponibilidad.objects.create(medico=doctor or self.doctor, fecha=self.day + timedelta(days=1),
                                             hora_inicio=time(10), hora_fin=time(10, 40))

    def snapshot(self, turno):
        turno.refresh_from_db()
        triaje = turno.triaje
        return (turno.pk, turno.paciente_id, turno.medico_id, turno.fecha_hora_creacion,
                triaje.pk, triaje.nivel_prioridad, triaje.respuesta_sintomas, triaje.fecha_hora_evaluacion)

    def test_complete_lifecycle_and_repetitions(self):
        turno = self.turn(today=True)
        original = self.snapshot(turno)
        self.login('SECRETARIA')
        self.assertEqual(self.call('presencia', turno).status_code, 200)
        turno.refresh_from_db()
        arrival = turno.fecha_hora_arribo
        self.assertEqual(turno.estado, 'PRESENTE')
        self.assertEqual(self.call('presencia', turno).status_code, 409)
        self.login('MEDICO')
        self.assertEqual(self.call('iniciar', turno).status_code, 200)
        self.assertEqual(self.call('iniciar', turno).status_code, 409)
        self.assertEqual(self.call('finalizar', turno).status_code, 200)
        self.assertEqual(self.call('finalizar', turno).status_code, 409)
        turno.refresh_from_db()
        self.assertEqual(turno.estado, 'COMPLETADO')
        self.assertEqual(turno.fecha_hora_arribo, arrival)
        self.assertLessEqual(turno.fecha_hora_creacion, arrival)
        self.assertLessEqual(arrival, turno.fecha_hora_inicio)
        self.assertLessEqual(turno.fecha_hora_inicio, turno.fecha_hora_cierre)
        self.assertEqual(self.snapshot(turno), original)
        self.block.refresh_from_db()
        self.assertEqual(self.block.estado, 'OCUPADO')
        self.assertEqual(turno.duracion_turno, 25)

    def test_presence_only_scheduled_day_before_or_after_hour(self):
        turno = self.turn()
        self.login('SECRETARIA')
        self.assertEqual(self.call('presencia', turno).status_code, 409)
        for hour in (0, 23):
            self.block.fecha = turno.fecha = timezone.localdate()
            self.block.save(update_fields=['fecha'])
            turno.save(update_fields=['fecha'])
            now = timezone.make_aware(datetime.combine(turno.fecha, time(hour, 30)))
            # Isolated coherent historical creation, not generated by the API.
            turno.fecha_hora_creacion = now - timedelta(days=1)
            turno.save(update_fields=['fecha_hora_creacion'])
            with patch('dominio.turnos.timezone.now', return_value=now):
                self.assertEqual(self.call('presencia', turno).status_code, 200)
            turno.estado, turno.fecha_hora_arribo = 'RESERVADO', None
            turno.save(update_fields=['estado', 'fecha_hora_arribo'])

