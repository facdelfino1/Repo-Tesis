class OperacionesConcurrencyTests(TransactionTestCase):
    parallel = test_password_reset.PasswordConcurrencyTests.parallel
    setUp = test_turnos.ReservaConcurrencyTests.setUp

    def setUp(self):
        test_turnos.ReservaConcurrencyTests.setUp(self)
        from .models import Secretaria
        import secrets
        self.secretary = Usuario.objects.create_user('secretary-race@example.com', secrets.token_urlsafe(24),
            rol='SECRETARIA', nombre='S', apellido='Race', dni='8', telefono='1')
        Secretaria.objects.create(usuario=self.secretary, legajo='RACE')
        self.turn = reservar_turno(self.patients[0], self.doctors[0].pk, self.blocks[0].pk,
                                  {'fiebre': False, 'dificultadRespirar': False, 'dolor': 0})
        self.destination = Disponibilidad.objects.create(medico=self.doctors[0], fecha=self.day + timedelta(days=1),
                                                        hora_inicio=time(9), hora_fin=time(9, 40))

    def result(self, function, *args, **kwargs):
        try:
            function(*args, **kwargs)
            return 200
        except APIException as error:
            return error.status_code

    def move(self, turno=None, target=None):
        return self.result(modificar_turno, self.secretary, (turno or self.turn).pk,
                           (target or self.destination).pk, medico_id=self.doctors[0].pk)

    def second_turn(self):
        block = Disponibilidad.objects.create(medico=self.doctors[0], fecha=self.day, hora_inicio=time(10), hora_fin=time(10, 20))
        turno = reservar_turno(self.patients[1], self.doctors[0].pk, block.pk,
                              {'fiebre': False, 'dificultadRespirar': False, 'dolor': 0})
        return turno, block

    def assert_single_consumer(self):
        for block in Disponibilidad.objects.all():
            count = block.turnos.exclude(estado='CANCELADO').count()
            self.assertLessEqual(count, 1)
            self.assertEqual(block.estado == 'OCUPADO', bool(count))

    def test_two_modifications_same_destination(self):
        other, _ = self.second_turn()
        self.assertEqual(sorted(self.parallel([self.move, lambda: self.move(other)])), [200, 409])
        self.assert_single_consumer()

    def test_modification_vs_new_reservation(self):
        def reserve():
            return self.result(reservar_turno, self.patients[1], self.doctors[0].pk, self.destination.pk,
                               {'fiebre': False, 'dificultadRespirar': False, 'dolor': 0})
        self.assertEqual(sorted(self.parallel([self.move, reserve])), [200, 409])
        self.assert_single_consumer()

    def test_modification_vs_cancellation(self):
        result = self.parallel([self.move, lambda: self.result(cancelar_turno, self.secretary, self.turn.pk,
                                                              medico_id=self.doctors[0].pk)])
        self.assertIn(result, ([200, 200], [409, 200]))
        self.turn.refresh_from_db()
        self.assertEqual(self.turn.estado, 'CANCELADO')
        self.assert_single_consumer()

    def test_modification_vs_blocking_destination(self):
        result = self.parallel([self.move, lambda: self.result(set_blocked, self.doctors[0].usuario,
                                self.doctors[0].pk, self.destination.pk, blocked=True)])
        self.assertIn(result, ([200, 409], [409, 200]))
        self.destination.refresh_from_db()
        self.assertEqual(self.destination.estado, 'OCUPADO' if result[0] == 200 else 'BLOQUEADO')

    def prepare_today(self):
        self.turn.fecha = self.blocks[0].fecha = timezone.localdate()
        self.turn.save(update_fields=['fecha']); self.blocks[0].save(update_fields=['fecha'])

    def test_presence_vs_cancellation(self):
        self.prepare_today()
        result = self.parallel([
            lambda: self.result(registrar_presencia, self.secretary, self.turn.pk, medico_id=self.doctors[0].pk),
            lambda: self.result(cancelar_turno, self.secretary, self.turn.pk, medico_id=self.doctors[0].pk)])
        self.assertEqual(sorted(result), [200, 409])
        self.turn.refresh_from_db()
        self.assertIn(self.turn.estado, ('PRESENTE', 'CANCELADO'))
        self.assert_single_consumer()

    def test_presence_vs_modification(self):
        self.prepare_today()
        result = self.parallel([lambda: self.result(registrar_presencia, self.secretary, self.turn.pk,
                                                    medico_id=self.doctors[0].pk), self.move])
        self.assertEqual(sorted(result), [200, 409])
        self.turn.refresh_from_db()
